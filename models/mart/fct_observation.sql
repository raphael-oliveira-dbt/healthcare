    observation_id,
    patient_id,
    encounter_id,
    observation_status,
    observation_category_code,
    observation_category_display,
    observation_code,
    observation_code_system,
    observation_code_display,
    coalesce(observation_code_display, observation_text, observation_code) as observation_name,
    observation_text,
    effective_at,
    date(effective_at) as effective_date,
    date_trunc(date(effective_at), month) as effective_month,
    issued_at,
    value_quantity,
    value_code,
    value_unit,
    value_quantity is not null as has_numeric_result,
    interpretation_code,
    interpretation_display,
    observation_status = 'final' as is_final_result,
    _source_file,
    _batch_id,
    _loaded_at
