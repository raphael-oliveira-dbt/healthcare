select
    observation_id,
    regexp_extract(patient_reference, r'([^/:]+)$') as patient_id,
    regexp_extract(encounter_reference, r'([^/:]+)$') as encounter_id,
    patient_reference,
    encounter_reference,
    observation_status,
    json_value(payload, '$.category[0].coding[0].code') as observation_category_code,
    json_value(payload, '$.category[0].coding[0].display') as observation_category_display,
    observation_code,
    json_value(payload, '$.code.coding[0].system') as observation_code_system,
    json_value(payload, '$.code.coding[0].display') as observation_code_display,
    observation_text,
    effective_at,
    safe_cast(json_value(payload, '$.issued') as timestamp) as issued_at,
    value_quantity,
    json_value(payload, '$.valueQuantity.code') as value_code,
    value_unit,
    json_value(payload, '$.interpretation[0].coding[0].code') as interpretation_code,
    json_value(payload, '$.interpretation[0].coding[0].display') as interpretation_display,
    payload,
    _source_file,
    _batch_id,
    _loaded_at
from {{ ref('stg_fhir_observation') }}
